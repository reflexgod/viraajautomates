// Measures the two main web fonts against the local fonts a browser shows
// before they arrive, and writes styles/fallbacks.css: @font-face rules that
// size and space Arial / Georgia (and Roboto, Android's sans) like Inter and
// Faculty Glyphic, so nothing moves when the real font swaps in.
//   node scripts/make-font-fallbacks.mjs   (then npm run css)
import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright-core';

const b64 = (p) => readFileSync(p).toString('base64');
const faces = {
  Inter: b64('public/fonts/inter-latin-wght.woff2'),
  'Faculty Glyphic': b64('public/fonts/faculty-glyphic-latin-400.woff2'),
  'Roboto Local': b64('node_modules/@fontsource/roboto/files/roboto-latin-400-normal.woff2'),
};
// Real copy from the page, so the average width matches what visitors read.
const SAMPLE = "I help businesses get found on Google and answer enquiries, even after hours. Customers usually go elsewhere for three reasons: they couldn't find you, they didn't trust what they saw, or nobody replied in time. Viraaj Automates";
const PAIRS = [
  // [family name, web font, local() names, measured as]
  ['Inter Fallback', 'Inter', 'local("Arial"), local("ArialMT")', 'Arial'],
  ['Inter Fallback Android', 'Inter', 'local("Roboto"), local("Roboto-Regular")', 'Roboto Local'],
  ['Faculty Glyphic Fallback', 'Faculty Glyphic', 'local("Georgia")', 'Georgia'],
];

const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage();
const metrics = await page.evaluate(async ({ faces, SAMPLE, PAIRS }) => {
  for (const [name, data] of Object.entries(faces)) {
    const f = new FontFace(name, `url(data:font/woff2;base64,${data})`);
    document.fonts.add(await f.load());
  }
  const ctx = document.createElement('canvas').getContext('2d');
  const m = (family) => {
    ctx.font = `400 1000px "${family}"`;
    const t = ctx.measureText(SAMPLE);
    return { width: t.width, ascent: t.fontBoundingBoxAscent, descent: t.fontBoundingBoxDescent };
  };
  return PAIRS.map(([, web, , local]) => ({ web: m(web), local: m(local) }));
}, { faces, SAMPLE, PAIRS });
await browser.close();

const pct = (v) => `${(v * 100).toFixed(2)}%`;
let css = '/* Generated by scripts/make-font-fallbacks.mjs: local fonts sized and\n   spaced like the web fonts, so text does not move when they swap in. */\n';
PAIRS.forEach(([family, web, src, local], i) => {
  const { web: w, local: l } = metrics[i];
  const size = w.width / l.width;
  css += `@font-face {\n  font-family: "${family}";\n  src: ${src};\n  size-adjust: ${pct(size)};\n  ascent-override: ${pct(w.ascent / 1000 / size)};\n  descent-override: ${pct(w.descent / 1000 / size)};\n  line-gap-override: 0%;\n}\n`;
  console.log(`${family} (${local} for ${web}): size-adjust ${pct(size)}`);
});
writeFileSync('styles/fallbacks.css', css);
console.log('styles/fallbacks.css written');
